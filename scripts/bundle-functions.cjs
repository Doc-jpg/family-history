/* Bundles each edge function into one file (supabase/functions/<name>/bundle.ts) so it can be
   pasted into the Supabase dashboard editor or deployed with the CLI. npm: imports stay external. */
const { build } = require('esbuild');
const fs = require('fs');
const path = require('path');
const dir = path.join(__dirname, '..', 'supabase', 'functions');
(async () => {
  for (const name of fs.readdirSync(dir)) {
    const entry = path.join(dir, name, 'index.ts');
    if (!fs.existsSync(entry)) continue;
    const out = path.join(dir, name, 'bundle.ts');
    await build({ entryPoints: [entry], bundle: true, format: 'esm', platform: 'neutral', target: 'esnext', outfile: out, external: ['npm:*', 'jsr:*', 'https://*', 'node:*'], logLevel: 'error', banner: { js: '// GENERATED by scripts/bundle-functions.cjs from index.ts. Do not edit; edit index.ts and rebuild.' } });
    console.log(`${name}: ${out} (${fs.statSync(out).size} bytes)`);
  }
})();
